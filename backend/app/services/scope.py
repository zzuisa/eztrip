_SUFFIX = re.compile(r"(自由行|旅游|旅行|之旅|攻略|游玩|玩玩|游|玩)$")
_PREFIX = re.compile(r"^(整个|全部|去|到|想去|我想去)")
_SPLIT = re.compile(r"\s*(?:、|,|，|;|；|/|／|\+|＋|&|→|->|和|与|及|跟|还有)\s*")


def _norm(s: str) -> str:
    s = re.sub(r"\s+", " ", str(s or "")).strip().lower()
    s = _PREFIX.sub("", s)
    s = _SUFFIX.sub("", s).strip()
    return s


def _index(table: Dict[str, Dict[str, Any]]) -> Dict[str, str]:
    idx: Dict[str, str] = {}
    for name, v in table.items():
        idx[name.lower()] = name
        for a in v.get("aliases", []):
            idx.setdefault(a.lower(), name)
    return idx


_I_CONT, _I_VAGUE, _I_COUNTRY = _index(_CONTINENTS), _index(_VAGUE), _index(_COUNTRIES)


def _ok(kind: str = "city") -> Dict[str, Any]:
    return {"level": "ok", "kind": kind, "allow_continue": True, "options": []}


def _clarify(kind: str, title: str, question: str, options: List[Dict[str, str]], allow_continue: bool, resolved: str = "") -> Dict[str, Any]:
    return {"level": "clarify", "kind": kind, "title": title, "question": question, "options": options[:8],
            "allow_continue": allow_continue, "resolved": resolved}


def is_hard_block(res: Dict[str, Any]) -> bool:
    return res.get("level") == "clarify" and not res.get("allow_continue", True)


def assess(location: str, days: int = 3) -> Dict[str, Any]:
    """纯静态评估（无网络）。返回 {level: ok|clarify, kind, title, question, options, allow_continue}."""
    raw = str(location or "").strip()
    key = _norm(raw)
    if not key:
        return _clarify("vague", "想去哪里？", "还没有填写目的地，先选一个或直接输入城市名。", _VAGUE["国外"]["options"], False)

    if key in _I_CONT:
        v = _CONTINENTS[_I_CONT[key]]
        name = _I_CONT[key]
        span = f"{days} 天" if days else "这段时间"
        return _clarify("continent", f"「{raw}」范围太大了",
                        f"{name}跨越几十个国家，{span}只适合深入一两座城市。想先从哪里开始？", v["options"], False)

    if key in _I_VAGUE:
        v = _VAGUE[_I_VAGUE[key]]
        return _clarify("vague", "再具体一点？", f"「{raw}」还不是一个具体的地点。选一个想去的城市，或直接输入城市名。", v["options"], False)

    parts = [p.strip() for p in _SPLIT.split(raw) if p and len(p.strip()) >= 2]
    if len(parts) >= 2 and not False and all(len(p) <= 20 for p in parts):
        opts = [{"label": p, "location": p, "hint": "先规划这一座，其余可以之后单独规划"} for p in parts[:6]]
        res = _clarify("multi", "要按顺序串联这几站吗？", f"你写了 {len(parts)} 个目的地。可以按这个顺序串联成一趟行程（每站单独安排，站间交通会算进来），也可以先只规划其中一座。", opts, False)
        res["chain"] = [p for p in parts[:4]]
        return res

    if key in _CITY_SIZED:
        return _ok("city")

    if key in _I_COUNTRY:
        name = _I_COUNTRY[key]
        v = _COUNTRIES[name]
        return _clarify("country", f"「{raw}」是整个国家",
                        f"{name}很大，按整国规划，每天可能要长途移动。建议选一座城市深入玩；也可以仍按整个国家规划。",
                        v["options"], True, resolved=name)

    return _ok("city")
